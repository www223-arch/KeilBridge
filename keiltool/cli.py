def cmd_configure(args: argparse.Namespace) -> int:
    """生成 KeilBridge 外部 CMake/OpenOCD/VS Code 工作区。"""

    model = parse_uvprojx(args.project)
    target = _pick_target(model, args.target)
    workspace_root = Path(args.workspace_root).resolve() if args.workspace_root else Path(model.inferred_project_root)
    recommendation = _write_backend_report(workspace_root, target, args.armclang_root, None)
    _print_backend_summary(recommendation)

    if args.backend == "auto":
        print("Auto mode only writes the backend diagnosis. Re-run configure with --backend gcc, armclang, or debug-only after choosing.")
        return 0
    if args.backend == "armclang":
        probe = _resolve_probe(target, args.probe)
        generated_dir = configure_armclang_workspace(workspace_root, target, probe=probe, armclang_root=args.armclang_root)
        print(f"Generated ArmClang workspace: {generated_dir}")
        print("Next:")
        print(f"  python -m keiltool.cli build --project \"{model.project_file}\" --target {target.name} --backend armclang")
        return 0
    if args.backend == "debug-only":
        probe = _resolve_probe(target, args.probe)
        generated_dir = configure_debug_only_workspace(
            workspace_root,
            target,
            probe=probe,
            executable=args.elf,
            keil_project_dir=model.keil_project_dir,
        )
        print(f"Generated Debug-only workspace: {generated_dir}")
        print("Open:")
        print(f"  {workspace_root / '.keilbridge' / f'KeilBridge_{_sanitize_name(target.name)}_debug.code-workspace'}")
        return 0

    probe = _resolve_probe(target, args.probe)
    generated_dir = configure_workspace(workspace_root, target, probe=probe)
    print(f"Generated workspace: {generated_dir}")
    print("Next:")
    print(f"  python -m keiltool.cli build --project \"{model.project_file}\" --target {target.name}")
    return 0


def cmd_build(args: argparse.Namespace) -> int:
    """调用 CMake 构建已生成的外部工作区。"""

    generated_dir, build_dir = _resolve_build_dirs(args)
    cmake = find_cmake(args.cmake)
    ninja = find_ninja(args.ninja)
    env = dict(os.environ)
    arm_gcc_root = find_arm_gcc_root(args.arm_gcc_root) if args.backend == "gcc" else ""
    if arm_gcc_root:
        env["ARM_GCC_ROOT"] = arm_gcc_root
    if args.backend == "armclang":
        tools = find_armclang_tools(args.armclang_root)
        missing = [name for name, path in tools.items() if not path]
        if missing:
            raise SystemExit(
                "ArmClang tools not found: "
                + ", ".join(missing)
                + ". Install Keil MDK ArmClang/Arm Compiler 6, add ARMCLANG/bin to PATH, "
                + "or pass --armclang-root / set ARMCLANG_ROOT."
            )
        for key, value in armclang_environment(args.armclang_root).items():
            if key == "PATH_PREFIX":
                env["PATH"] = value + os.pathsep + env.get("PATH", "")
            else:
                env[key] = value

    _run([
        cmake,
        "-S",
        str(generated_dir),
        "-B",
        str(build_dir),
        "-G",
        "Ninja",
        f"-DCMAKE_MAKE_PROGRAM={ninja}",
    ], cwd=generated_dir, env=env)
    _run([cmake, "--build", str(build_dir)], cwd=generated_dir, env=env)
    return 0


def cmd_openocd(args: argparse.Namespace) -> int:
    """打印或启动 OpenOCD 调试服务。

    MVP 阶段默认只生成命令，不强制后台启动，避免用户硬件未连接时误卡住。
    """

    model = parse_uvprojx(args.project)
    target = _pick_target(model, args.target)
    probe = _resolve_probe(target, args.probe)
    interface = {
        "stlink": "interface/stlink.cfg",
        "cmsis-dap": "interface/cmsis-dap.cfg",
        "daplink": "interface/cmsis-dap.cfg",
    }.get(probe, "interface/stlink.cfg")
    openocd = find_openocd(args.openocd)
    scripts = find_openocd_scripts(openocd)
    target_resolution = resolve_openocd_target(target, scripts)
    if not target_resolution.target_cfg:
        raise SystemExit(f"OpenOCD target could not be resolved: {target_resolution.reason}")
    command = [openocd]
    if scripts:
        command.extend(["-s", scripts])
    command.extend(["-f", interface, "-f", target_resolution.target_cfg])
    print(" ".join(command))
    if args.run:
        _run(command, cwd=Path.cwd())
    return 0


def _hardware_selection(args: argparse.Namespace) -> HardwareSelection:
    project = getattr(args, "project", None)
    device = str(getattr(args, "device", "") or "")
    target = str(getattr(args, "target", "") or "")
    vendor = str(getattr(args, "vendor", "") or "")
    if device and target:
        raise SystemExit("--target is valid only with --project.")
    if project and vendor:
        raise SystemExit("--vendor is valid only with --device.")
    try:
        return HardwareSelection(
            project=Path(project) if project else None,
            target=target,
            device=device,
            vendor=vendor,
            openocd=str(getattr(args, "openocd", "") or ""),
            scripts=str(getattr(args, "scripts", "") or ""),
            target_cfg=str(getattr(args, "target_cfg", "") or ""),
            logs_dir=(
                Path(getattr(args, "logs_dir"))
                if getattr(args, "logs_dir", None)
                else None
            ),
        )
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc


def _resolve_hardware(args: argparse.Namespace):
    try:
        return resolve_hardware_context(_hardware_selection(args))
    except (OSError, ValueError) as exc:
        raise SystemExit(str(exc)) from exc


def _run_hardware_operation(
    command_name: str,
    context: object,
    args: argparse.Namespace,
    action,
    *,
    metadata: dict[str, object] | None = None,
    artifact=None,
) -> int:
    config = getattr(context, "config")
    log_context = create_session_logs(
        getattr(context, "logs_dir"),
        device=str(getattr(context, "device")),
        task=command_name.upper().replace("-", "_"),
        metadata={
            "target_cfg": str(getattr(config, "target_cfg", "")),
            "interface_cfg": str(getattr(config, "interface_cfg", "")),
            **(metadata or {}),
        },
    )
    try:
        result = action(log_context)
    except (OSError, ValueError) as exc:
        log_context.finalize("operation_error")
        raise SystemExit(str(exc)) from exc
    outcome = str(getattr(result, "outcome", "failed"))
    log_context.finalize(outcome)
    artifact_payload = artifact(result) if artifact is not None else None
    payload = operation_payload(
        command_name,
        context,
        result,
        artifact=artifact_payload,
    )
    render_operation(payload, str(getattr(args, "output_format", "text")))
    return 0 if bool(getattr(result, "success", False)) else int(getattr(result, "returncode", 0)) or 1


