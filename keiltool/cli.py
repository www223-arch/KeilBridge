def _print_backend_summary(result) -> None:
    print(f"Recommended backend: {result.recommended}")
    for option in result.options:
        print(f"  [{option.status}] {option.backend}: {option.title}")
        if option.blockers:
            print(f"    blockers: {'; '.join(option.blockers)}")


def _run(command: list[str], cwd: Path, env: dict[str, str] | None = None) -> None:
    try:
        subprocess.run(command, cwd=cwd, env=env, check=True)
    except FileNotFoundError as exc:
        raise SystemExit(f"Command not found: {command[0]}. Please install it or pass an explicit path.") from exc
    except subprocess.CalledProcessError as exc:
        raise SystemExit(exc.returncode) from exc


def _resolve_build_dirs(args: argparse.Namespace) -> tuple[Path, Path]:
    """解析 build 使用的 generated/build 目录。

    推荐传入 `--project/--target`，这样 build 会自动使用目标工程根目录下的
    `.keilbridge`。不传 project 时保留旧行为，使用当前目录下的 `.keilbridge`。
    """

    if args.project:
        model = parse_uvprojx(args.project)
        _pick_target(model, args.target)
        workspace_root = Path(args.workspace_root).resolve() if args.workspace_root else Path(model.inferred_project_root)
        if args.backend == "armclang":
            return (
                workspace_root / ".keilbridge" / "generated" / "armclang",
                workspace_root / ".keilbridge" / "build" / "armclang-debug",
            )
        return (
            workspace_root / ".keilbridge" / "generated",
            workspace_root / ".keilbridge" / "build" / "gcc-debug",
        )

    generated_dir = Path(args.generated_dir).resolve()
    build_dir = Path(args.build_dir).resolve()
    return generated_dir, build_dir


